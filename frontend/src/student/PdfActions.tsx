import { useEffect, useRef, useState } from 'react'
import { useStudentQuery } from './queries'
import { downloadPDF, generatePDF, getPDFStatus, StudentError } from './service'
import { useCountdown } from '../auth/hooks'

export function PdfActions({ versionId }: { versionId?: string }) {
  const query = useStudentQuery(['pdf', versionId ?? 'latest'], signal => getPDFStatus(versionId, signal))
  const [busy, setBusy] = useState(false), [message, setMessage] = useState(''), [until, setUntil] = useState(0)
  const remaining = useCountdown(until), controller = useRef<AbortController | null>(null), inFlight = useRef(false), objectUrls = useRef(new Set<string>())
  useEffect(() => () => { controller.current?.abort(); for (const url of objectUrls.current) URL.revokeObjectURL(url); objectUrls.current.clear() }, [])
  const status = query.data
  const { refetch, dataUpdatedAt, isError } = query
  const preparing = status?.status === 'PENDING' || status?.status === 'GENERATING'
  useEffect(() => {
    if (!preparing || isError) return
    const timer = setTimeout(() => void refetch(), 2000)
    return () => clearTimeout(timer)
  }, [preparing, dataUpdatedAt, isError, refetch])
  async function action(kind: 'generate' | 'download') {
    if (inFlight.current || Date.now() < until) return
    inFlight.current = true; setBusy(true); setMessage('')
    const request = new AbortController(); controller.current = request
    try {
      if (kind === 'generate') {
        await generatePDF(versionId, request.signal)
        if (!request.signal.aborted) await query.refetch()
      } else {
        const { blob, filename } = await downloadPDF(versionId, request.signal)
        if (request.signal.aborted) return
        const url = URL.createObjectURL(blob); objectUrls.current.add(url)
        const link = document.createElement('a'); link.href = url; link.download = filename; document.body.append(link); link.click(); link.remove()
        // Drop the private object URL after the browser has started the download.
        setTimeout(() => { URL.revokeObjectURL(url); objectUrls.current.delete(url) }, 1000)
        setMessage('Registered Passport PDF downloaded.')
      }
    } catch (error) {
      if (request.signal.aborted) return
      setMessage(error instanceof Error ? error.message : 'The PDF is unavailable.')
      if (error instanceof StudentError) {
        setUntil(Date.now() + Math.max(error.retryAfter, error.status === 409 ? 2 : 0) * 1000)
        if (error.status === 409) await query.refetch()
      }
    } finally { inFlight.current = false; if (!request.signal.aborted) setBusy(false) }
  }
  return <section className="student-pdf" aria-label="Official Passport PDF"><h2>Passport PDF</h2>
    <p>Generated by the university backend from this issued snapshot, using the BTU template.</p>
    {query.isPending && <p role="status">Checking registered PDF…</p>}
    {query.isError && <><p role="alert">{query.error.message}</p><button className="button" onClick={() => void query.refetch()}>Retry PDF status</button></>}
    {status && !query.isError && <><p role="status">PDF status: {status.status}</p>{status.generated_at && <p>Generated: {status.generated_at}</p>}{status.status === 'FAILED' && <p role="alert">The previous generation failed. You may retry.</p>}
      {preparing && <p role="status">Generation in progress. Checking status automatically.</p>}
      {status.available_for_download ? <button className="button primary" disabled={busy || remaining > 0} onClick={() => void action('download')}>Download registered PDF</button> : <button className="button primary" disabled={busy || preparing || remaining > 0} onClick={() => void action('generate')}>{status.status === 'FAILED' ? 'Retry PDF generation' : 'Generate Passport PDF'}</button>}
    </>}
    {busy && <p role="status">Processing PDF…</p>}{message && <p role="status">{message}</p>}{remaining > 0 && <p role="status">Retry in {remaining} seconds.</p>}
  </section>
}
